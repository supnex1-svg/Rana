// بترجّع نفس الخدمة، ولو اللغة عربي والـ id موجود بتبدّل العنوان والوصف والنقط
export function localizeService<T extends ServiceLike>(service: T, lang: Lang): T {
  if (lang !== 'ar') return service;
  const ar = SERVICES_AR[service.id];
  return ar ? { ...service, ...ar } : service;
}